#!/usr/bin/env python3
"""Generate the native app catalog; no build-time Python dependency is required."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / 'xbox/locales/interface.json'
HEADER = ROOT / 'gpu/shim/spartanport_ui_catalog.h'


def generate():
    rows = json.loads(CATALOG.read_text(encoding='utf-8'))
    keys = set()
    for row in rows:
        if len(row) != 3 or not all(isinstance(s, str) and s for s in row):
            raise ValueError('Each entry needs nonempty English, Brazilian Portuguese and Spanish text')
        if row[0] in keys:
            raise ValueError(f'Duplicate key: {row[0]}')
        if any(text.count('{}') != row[0].count('{}') for text in row):
            raise ValueError(f'Placeholder mismatch: {row[0]}')
        keys.add(row[0])
    lines = ['// SPDX-License-Identifier: GPL-2.0-or-later',
             '// Generated by scripts/generate_xbox_translations.py from xbox/locales/interface.json.',
             '#pragma once', '#include <array>', '#include <string_view>',
             'namespace SpartanUi {', 'struct Entry { const char* en; const char* pt; const char* es; };',
             f'inline constexpr std::array<Entry, {len(rows)}> Catalog = {{{{']
    for row in sorted(rows):
        lines.append('    {' + ', '.join(json.dumps(s, ensure_ascii=False) for s in row) + '},')
    lines += ['}};', '} // namespace SpartanUi', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not HEADER.exists() or HEADER.read_text(encoding='utf-8') != content:
            parser.exit(1, 'Native catalog is stale; run scripts/generate_xbox_translations.py\n')
    else:
        HEADER.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    main()
